import os
from tqdm import tqdm

# Root path
LABEL_ROOT = "/content/datasets/content/datasets/group_celeb/labels"
yaml_path = "/content/group_celeb.yaml"

# Collect all class IDs
class_ids = set()
for split in ["train", "val", "test"]:
    label_dir = os.path.join(LABEL_ROOT, split)
    for file in os.listdir(label_dir):
        if file.endswith(".txt"):
            with open(os.path.join(label_dir, file)) as f:
                for line in f:
                    parts = line.strip().split()
                    if len(parts) > 0:
                        class_ids.add(parts[0])

class_ids = sorted(list(class_ids))
id_to_index = {cid: i for i, cid in enumerate(class_ids)}

print(f"[INFO] Found {len(class_ids)} unique celeb IDs.")
print(f"[INFO] Example mapping: {list(id_to_index.items())[:5]}")

# Rewrite label files with numeric IDs
for split in ["train", "val", "test"]:
    label_dir = os.path.join(LABEL_ROOT, split)
    for file in tqdm(os.listdir(label_dir), desc=f"Fixing {split} labels"):
        if not file.endswith(".txt"):
            continue
        lines_out = []
        with open(os.path.join(label_dir, file)) as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) != 5:
                    continue
                old_id = parts[0]
                if old_id not in id_to_index:
                    continue
                new_id = id_to_index[old_id]
                lines_out.append(f"{new_id} {' '.join(parts[1:])}")
        with open(os.path.join(label_dir, file), "w") as f:
            f.write("\n".join(lines_out))

print("[INFO] All label files updated with numeric class IDs.")

