import os, cv2, random, numpy as np
from glob import glob
from tqdm import tqdm
from PIL import Image
from torchvision import transforms

# === CONFIGURATION ===
CELEB_ROOT = "/content/drive/MyDrive/Celebrity Image Subsets"
YOLO_DATASET_ROOT = "/content/datasets/group_celeb"
CANVAS_SIZE = (1280, 720)   # width x height
FACE_SIZE = (128, 128)      # smaller faces so more fit
TOTAL_IMAGES = 10000
MIN_FACES = 5
MAX_FACES = 40
OVERLAP_TOLERANCE = 0.05    # allow up to 5% overlap between faces

# Collect celeb folders
celeb_folders = [f for f in glob(os.path.join(CELEB_ROOT, "images_*")) if os.path.isdir(f)]
print(f"[INFO] Found {len(celeb_folders)} celebrity folders.")

# Augmentation pipeline
augment = transforms.Compose([
    transforms.RandomHorizontalFlip(p=0.5),
    transforms.ColorJitter(brightness=0.3, contrast=0.3, saturation=0.3),
    transforms.RandomRotation(degrees=15),
])

def random_augment(image):
    image = Image.fromarray(cv2.cvtColor(image, cv2.COLOR_BGR2RGB))
    image = augment(image)
    return cv2.cvtColor(np.array(image), cv2.COLOR_RGB2BGR)

# Helper: placement with overlap tolerance
def get_random_position(existing_boxes, w, h, face_w, face_h, max_tries=50):
    for _ in range(max_tries):
        x = random.randint(0, w - face_w)
        y = random.randint(0, h - face_h)
        new_box = [x, y, x + face_w, y + face_h]
        overlap = False
        for (x1, y1, x2, y2) in existing_boxes:
            # Calculate intersection
            inter_x1 = max(x1, new_box[0])
            inter_y1 = max(y1, new_box[1])
            inter_x2 = min(x2, new_box[2])
            inter_y2 = min(y2, new_box[3])
            if inter_x1 < inter_x2 and inter_y1 < inter_y2:
                inter_area = (inter_x2 - inter_x1) * (inter_y2 - inter_y1)
                box_area = face_w * face_h
                if inter_area / box_area > OVERLAP_TOLERANCE:
                    overlap = True
                    break
        if not overlap:
            return new_box
    return None

# Split ratios
train_ratio, val_ratio, test_ratio = 0.8, 0.1, 0.1

for i in tqdm(range(TOTAL_IMAGES), desc="Generating synthetic dataset"):
    # Decide dataset split
    if i < int(TOTAL_IMAGES * train_ratio):
        split = "train"
    elif i < int(TOTAL_IMAGES * (train_ratio + val_ratio)):
        split = "val"
    else:
        split = "test"

    img_dir = os.path.join(YOLO_DATASET_ROOT, "images", split)
    label_dir = os.path.join(YOLO_DATASET_ROOT, "labels", split)

    # Blank canvas
    canvas = np.ones((CANVAS_SIZE[1], CANVAS_SIZE[0], 3), dtype=np.uint8) * 255
    label_lines, boxes = [], []

    selected_folders = random.sample(celeb_folders, random.randint(MIN_FACES, MAX_FACES))

    for folder in selected_folders:
        celeb_id = folder.split("_")[-1]  # e.g. images_<228> -> <228>
        image_paths = glob(os.path.join(folder, "*.jpg"))
        if not image_paths:
            continue
        face = cv2.imread(random.choice(image_paths))
        if face is None:
            continue
        face = random_augment(face)
        face = cv2.resize(face, FACE_SIZE)

        box = get_random_position(boxes, CANVAS_SIZE[0], CANVAS_SIZE[1], FACE_SIZE[0], FACE_SIZE[1])
        if box is None:
            continue
        x1, y1, x2, y2 = box
        boxes.append(box)
        canvas[y1:y2, x1:x2] = face

        # YOLO format (class x_center y_center w h)
        x_center = ((x1 + x2) / 2) / CANVAS_SIZE[0]
        y_center = ((y1 + y2) / 2) / CANVAS_SIZE[1]
        w_norm = FACE_SIZE[0] / CANVAS_SIZE[0]
        h_norm = FACE_SIZE[1] / CANVAS_SIZE[1]
        label_lines.append(f"{celeb_id} {x_center:.6f} {y_center:.6f} {w_norm:.6f} {h_norm:.6f}")

    # Save image + labels
    img_name = f"group_{i:05d}.jpg"
    label_name = f"group_{i:05d}.txt"
    cv2.imwrite(os.path.join(img_dir, img_name), canvas)
    with open(os.path.join(label_dir, label_name), "w") as f:
        f.write("\n".join(label_lines))

print(f"[INFO] Generated {TOTAL_IMAGES} group images with face size {FACE_SIZE} and mild overlap tolerance.")

