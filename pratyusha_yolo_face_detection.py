class TrainCelebAYOLO:
    def __init__(self, celeba_root, output_root, num_classes=44):
        """Initialize YOLO training pipeline for CelebA composites"""
        self.celeba_root = Path(celeba_root)
        self.output_root = Path(output_root)
        self.num_classes = num_classes
        self.img_size = 640
        self.celeb_id_to_index = {}  # will be filled later
        self.output_root.mkdir(parents=True, exist_ok=True)

    # =========================================================================
    # STEP 4: Split dataset
    # =========================================================================
    def step4_split_dataset(self, composite_dir, train_ratio=0.8):
        """Split composite images into train/val sets"""
        print("\nStep 4: Splitting into train/val sets")

        dataset_dir = self.output_root / "yolo_dataset"
        train_img_dir = dataset_dir / "images" / "train"
        val_img_dir = dataset_dir / "images" / "val"
        train_label_dir = dataset_dir / "labels" / "train"
        val_label_dir = dataset_dir / "labels" / "val"

        for d in [train_img_dir, val_img_dir, train_label_dir, val_label_dir]:
            d.mkdir(parents=True, exist_ok=True)

        all_images = list(Path(composite_dir).glob('*.jpg'))
        valid_images = []

        for img_path in all_images:
            label_path = img_path.with_suffix('.txt')
            if label_path.exists():
                with open(label_path, 'r') as f:
                    if f.read().strip():
                        valid_images.append(img_path)

        print(f"Found {len(valid_images)} images with valid annotations")

        if len(valid_images) == 0:
            print("ERROR: No valid images found!")
            return None

        random.shuffle(valid_images)
        split_idx = int(len(valid_images) * train_ratio)
        train_images = valid_images[:split_idx]
        val_images = valid_images[split_idx:]

        for img_path in train_images:
            shutil.copy(img_path, train_img_dir / img_path.name)
            lbl_path = img_path.with_suffix('.txt')
            if lbl_path.exists():
                shutil.copy(lbl_path, train_label_dir / lbl_path.name)

        for img_path in val_images:
            shutil.copy(img_path, val_img_dir / img_path.name)
            lbl_path = img_path.with_suffix('.txt')
            if lbl_path.exists():
                shutil.copy(lbl_path, val_label_dir / lbl_path.name)

        print(f"Train: {len(train_images)}, Val: {len(val_images)}")
        return dataset_dir

    # =========================================================================
    # STEP 5: Data Augmentation
    # =========================================================================
    def step5_augment_dataset(self, dataset_dir, augmentation_factor=1):
        """Apply data augmentation to training set"""
        print(f"\nStep 5: Augmenting dataset (factor={augmentation_factor})")

        train_img_dir = dataset_dir / "images" / "train"
        train_label_dir = dataset_dir / "labels" / "train"

        transform = A.Compose([
            A.RandomBrightnessContrast(p=0.3),
            A.HueSaturationValue(p=0.3),
            A.GaussNoise(p=0.2),
            A.Blur(blur_limit=3, p=0.2),
            # A.RandomRotate90(p=0.3),
        ], bbox_params=A.BboxParams(format='yolo', label_fields=['class_labels']))

        images = list(train_img_dir.glob('*.jpg'))
        original_count = len(images)
        successful = 0

        print(f"Augmenting {original_count} images...")

        for idx, img_path in enumerate(images):
            label_path = train_label_dir / img_path.with_suffix('.txt').name
            if not label_path.exists():
                continue

            img = cv2.imread(str(img_path))
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

            bboxes, class_labels = self._read_yolo_annotations(label_path)

            for aug_idx in range(augmentation_factor):
                try:
                    augmented = transform(image=img, bboxes=bboxes, class_labels=class_labels)

                    aug_img = augmented['image']
                    aug_bboxes = augmented['bboxes']
                    aug_labels = augmented['class_labels']

                    aug_name = f"{img_path.stem}_aug{aug_idx}.jpg"
                    aug_img_bgr = cv2.cvtColor(aug_img, cv2.COLOR_RGB2BGR)
                    cv2.imwrite(str(train_img_dir / aug_name), aug_img_bgr)

                    aug_label_name = f"{img_path.stem}_aug{aug_idx}.txt"
                    self._write_yolo_annotations(train_label_dir / aug_label_name, aug_bboxes, aug_labels)

                    successful += 1
                except Exception as e:
                    print(f"Augmentation failed for {img_path.name}: {e}")
                    continue

            if (idx + 1) % 50 == 0:
                print(f"Progress: {idx + 1}/{original_count} images processed")

        augmented_count = len(list(train_img_dir.glob('*.jpg')))
        print(f"✓ Dataset augmented: {original_count} → {augmented_count} images")
        print(f"✓ Successfully created {successful} augmented images")

        return augmented_count

    # =========================================================================
    # Helper: Read YOLO Annotations
    # =========================================================================
    def _read_yolo_annotations(self, label_path):
        """Read YOLO format annotations"""
        bboxes, class_labels = [], []
        with open(label_path, 'r') as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) == 5:
                    class_id = int(float(parts[0]))
                    bbox = [float(x) for x in parts[1:]]
                    bboxes.append(bbox)
                    class_labels.append(class_id)
        return bboxes, class_labels

    # =========================================================================
    # Helper: Write YOLO Annotations
    # =========================================================================
    def _write_yolo_annotations(self, label_path, bboxes, class_labels):
        """Write YOLO format annotations (using correct class indices)"""
        with open(label_path, 'w') as f:
            for bbox, celeb_id in zip(bboxes, class_labels):
                # Convert raw celeb ID → class index
                class_idx = self.celeb_id_to_index.get(celeb_id, celeb_id)
                f.write(f"{class_idx} {bbox[0]:.6f} {bbox[1]:.6f} {bbox[2]:.6f} {bbox[3]:.6f}\n")

    # =========================================================================
    # STEP 6: Create YAML Config + Mapping
    # =========================================================================
    def step6_create_yaml_config(self, dataset_dir, celebrity_names):
        """Create YAML configuration file for YOLOv8"""
        yaml_path = dataset_dir / "dataset.yaml"

        sorted_celeb_ids = sorted(celebrity_names.keys())
        class_names = [
            celebrity_names[cid].replace("images__", "").rstrip("_")
            for cid in sorted_celeb_ids
        ]

        actual_num_classes = len(class_names)

        config = {
            'path': str(dataset_dir.absolute()),
            'train': 'images/train',
            'val': 'images/val',
            'nc': actual_num_classes,
            'names': class_names
        }

        with open(yaml_path, 'w') as f:
            yaml.dump(config, f, default_flow_style=False)

        print(f"\nDataset config saved to {yaml_path}")
        print(f"Number of classes: {actual_num_classes}")
        print(f"Sample class names: {class_names[:5]}")

        # ✅ Mapping for annotation writing
        self.celeb_id_to_index = {cid: idx for idx, cid in enumerate(sorted_celeb_ids)}
        print(f"\nCelebrity ID to Index mapping (first 5):")
        for idx, cid in enumerate(sorted_celeb_ids[:5]):
            print(f"  Celebrity {cid} -> Class Index {idx} ({class_names[idx]})")

        return yaml_path

    def step6b_convert_labels_to_class_indices(self, dataset_dir):
        """Convert all existing label files from celeb IDs → YOLO class indices"""
        print("\nStep 6b: Converting all label files to YOLO class indices...")

        label_dirs = [
            dataset_dir / "labels" / "train",
            dataset_dir / "labels" / "val"
        ]

        total_converted = 0
        for lbl_dir in label_dirs:
            for lbl_path in lbl_dir.glob("*.txt"):
                lines_out = []
                with open(lbl_path, "r") as f:
                    for line in f:
                        parts = line.strip().split()
                        if len(parts) != 5:
                            continue
                        celeb_id = int(float(parts[0]))
                        if celeb_id not in self.celeb_id_to_index:
                            print(f"⚠️ Unknown celeb ID {celeb_id} in {lbl_path.name}, skipping.")
                            continue
                        class_idx = self.celeb_id_to_index[celeb_id]
                        parts[0] = str(class_idx)
                        lines_out.append(" ".join(parts))
                # overwrite file
                with open(lbl_path, "w") as f:
                    f.write("\n".join(lines_out))
                total_converted += 1

        print(f"✓ Converted {total_converted} label files to YOLO class indices.")


    # =========================================================================
    # STEP 7: Train YOLOv8
    # =========================================================================
    def step7_train_yolov8(self, yaml_path, epochs=30, batch_size=16):
        """Train YOLOv8 model"""
        print(f"\nTraining YOLOv8 model for {epochs} epochs...")
        model = YOLO('yolov8n.pt')

        results = model.train(
            data=str(yaml_path),
            epochs=epochs,
            imgsz=self.img_size,
            batch=batch_size,
            name='celeba_detection',
            patience=20,
            save=True,
            device=0
        )

        print("\n✓ Training completed!")
        return model, results

    # =========================================================================
    # STEP 8: Evaluate model
    # =========================================================================
    def step8_evaluate_model(self, model_path, yaml_path):
        """Evaluate trained model"""
        print("\nStep 8: Evaluating model")

        model = YOLO(model_path)
        metrics = model.val(data=str(yaml_path))

        print(f"\nmAP50: {metrics.box.map50:.4f}")
        print(f"mAP50-95: {metrics.box.map:.4f}")
        print(f"Precision: {metrics.box.mp:.4f}")
        print(f"Recall: {metrics.box.mr:.4f}")

        return metrics


