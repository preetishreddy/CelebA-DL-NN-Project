class CelebAYOLOProcessor:
    def __init__(self, celeba_root, output_root, num_classes):
        """Initialize the processor"""
        self.celeba_root = Path(celeba_root)
        self.output_root = Path(output_root)
        self.num_classes = num_classes
        self.img_size = 640
        self.output_root.mkdir(parents=True, exist_ok=True)


    def _resize_with_padding(self, img, target_size):
        """Resize image maintaining aspect ratio with padding"""
        h, w = img.shape[:2]
        scale = min(target_size/h, target_size/w)
        new_h, new_w = int(h*scale), int(w*scale)

        resized = cv2.resize(img, (new_w, new_h))

        padded = np.zeros((target_size, target_size, 3), dtype=np.uint8)
        y_offset = (target_size - new_h) // 2
        x_offset = (target_size - new_w) // 2
        padded[y_offset:y_offset+new_h, x_offset:x_offset+new_w] = resized

        return padded

    def step1_resize_images(self, input_dir, output_dir):
        """Resize all images to 640x640"""
        print(f"\nStep 1: Resizing images to {self.img_size}x{self.img_size}")

        output_path = Path(output_dir)
        output_path.mkdir(parents=True, exist_ok=True)

        input_path = Path(input_dir)
        celeb_dirs = [d for d in input_path.iterdir() if d.is_dir()]

        total_processed = 0

        for class_dir in sorted(celeb_dirs):
            class_id = class_dir.name
            output_class_dir = output_path / class_id
            output_class_dir.mkdir(parents=True, exist_ok=True)

            images = []
            for ext in ['*.jpg', '*.jpeg', '*.png', '*.JPG', '*.JPEG', '*.PNG']:
                images.extend(class_dir.glob(ext))

            if not images:
                continue

            for img_file in images:
                try:
                    img = cv2.imread(str(img_file))
                    if img is None:
                        continue

                    resized = self._resize_with_padding(img, self.img_size)
                    output_file = output_class_dir / img_file.name
                    cv2.imwrite(str(output_file), resized)
                    total_processed += 1

                    if total_processed % 100 == 0:
                        print(f"Progress: {total_processed} images...")
                except Exception as e:
                    print(f"Error: {e}")

        print(f"✓ Resized {total_processed} images")
        return total_processed

    def _create_single_composite(self, class_images, n_celebs):
        """Create a single composite image with n celebrities"""
        canvas_size = self.img_size
        # Custom grid layouts for better arrangements
        if n_celebs == 4:
            grid_rows, grid_cols = 2, 2
        elif n_celebs == 6:
            grid_rows, grid_cols = 2, 3
        elif n_celebs == 10:
            grid_rows, grid_cols = 2, 5  # 2x5 grid for 10 celebrities
        else:
            # Default: square-ish grid
            grid_size = int(np.ceil(np.sqrt(n_celebs)))
            grid_rows, grid_cols = grid_size, grid_size

        # Calculate canvas dimensions based on grid
        cell_width = canvas_size // grid_cols
        cell_height = canvas_size // grid_rows

        # Adjust canvas to fit grid exactly (no black bars)
        canvas_width = cell_width * grid_cols
        canvas_height = cell_height * grid_rows

        composite = np.ones((canvas_size, canvas_size, 3), dtype=np.uint8) * 255

        selected_classes = random.sample(list(class_images.keys()),
                                        min(n_celebs, len(class_images)))

        grid_size = int(np.ceil(np.sqrt(n_celebs)))
        cell_size = canvas_size // grid_size

        annotations = []

        for i, class_id in enumerate(selected_classes):
            img_path = random.choice(class_images[class_id])
            img = cv2.imread(str(img_path))

            if img is None:
                continue

            row = i // grid_size
            col = i % grid_size

            padding = 0  # No padding
            target_size = cell_size - 2*padding

            # Ensure target_size is positive
            if target_size <= 0:
                continue

            img_resized = cv2.resize(img, (target_size, target_size))

            y_start = row * cell_size + padding
            x_start = col * cell_size + padding
            y_end = y_start + target_size
            x_end = x_start + target_size

            composite[y_start:y_end, x_start:x_end] = img_resized

            # Calculate normalized coordinates (0-1 range)
            x_center = ((x_start + x_end) / 2) / canvas_size
            y_center = ((y_start + y_end) / 2) / canvas_size
            width = target_size / canvas_size
            height = target_size / canvas_size

            # Ensure all values are valid (between 0 and 1)
            if 0 < x_center < 1 and 0 < y_center < 1 and 0 < width < 1 and 0 < height < 1:
                annotations.append({
                    'class_id': int(class_id),
                    'x_center': float(x_center),
                    'y_center': float(y_center),
                    'width': float(width),
                    'height': float(height)
                })

        return composite, annotations

    def _save_yolo_annotations(self, filepath, annotations):
        """Save annotations in YOLO format"""
        with open(filepath, 'w') as f:
            for ann in annotations:
                class_id = int(ann['class_id'])
                f.write(f"{class_id} {ann['x_center']:.6f} "
                       f"{ann['y_center']:.6f} {ann['width']:.6f} "
                       f"{ann['height']:.6f}\n")

    def step3_create_composite_images(self, resized_dir, configs):
        """Create composite images with N celebrities per image"""
        print("\nStep 3: Creating composite images")

        class_images = {}
        resized_path = Path(resized_dir)
        celeb_dirs = [d for d in resized_path.iterdir() if d.is_dir()]

        for class_dir in celeb_dirs:
            class_id = int(class_dir.name)
            images = []
            for ext in ['*.jpg', '*.jpeg', '*.png']:
                images.extend(class_dir.glob(ext))
            if images:
                class_images[class_id] = images

        print(f"Total celebrities with images: {len(class_images)}")

        if len(class_images) < max(configs):
            configs = [c for c in configs if c <= len(class_images)]

        results = {}

        for n_celebs in configs:
            print(f"\nCreating composites with {n_celebs} celebrities...")
            config_dir = self.output_root / f"composite_{n_celebs}"
            config_dir.mkdir(parents=True, exist_ok=True)

            num_composites = min(1000, len(class_images) * 5)
            valid_composites = 0
            attempts = 0
            max_attempts = num_composites * 2

            while valid_composites < num_composites and attempts < max_attempts:
                composite, annotations = self._create_single_composite(class_images, n_celebs)

                if len(annotations) > 0:
                    img_name = f"composite_{valid_composites:05d}.jpg"
                    cv2.imwrite(str(config_dir / img_name), composite)

                    ann_name = f"composite_{valid_composites:05d}.txt"
                    self._save_yolo_annotations(config_dir / ann_name, annotations)

                    valid_composites += 1

                    if valid_composites % 100 == 0:
                        print(f"Created {valid_composites}/{num_composites} valid composites...")

                attempts += 1

            results[n_celebs] = config_dir
            print(f"✓ Created {valid_composites} valid composite images")

        return results


    def _read_yolo_annotations(self, label_path):
        """Read YOLO format annotations"""
        bboxes = []
        class_labels = []

        with open(label_path, 'r') as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) == 5:
                    class_id = int(float(parts[0]))
                    bbox = [float(x) for x in parts[1:]]
                    bboxes.append(bbox)
                    class_labels.append(class_id)

        return bboxes, class_labels

    def _write_yolo_annotations(self, label_path, bboxes, class_labels):
        """Write YOLO format annotations"""
        with open(label_path, 'w') as f:
            for bbox, class_id in zip(bboxes, class_labels):
                class_id = int(class_id)
                f.write(f"{class_id} {bbox[0]:.6f} {bbox[1]:.6f} "
                       f"{bbox[2]:.6f} {bbox[3]:.6f}\n")



