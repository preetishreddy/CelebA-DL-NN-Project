    print(f"\nExtracting and organizing zip file...")
    print(f"Source: {zip_path}")
    print(f"Destination: {extract_to}")

    extract_path = Path(extract_to)
    extract_path.mkdir(parents=True, exist_ok=True)

    zip_source = Path(zip_path)

    # Handle different cases
    if zip_source.is_dir():
        print(f"Source is a directory, searching for .zip files...")
        zip_files = list(zip_source.glob('*.zip'))
        if not zip_files:
            print(f"No .zip files found, checking for images...")
            temp_extract = zip_source
        else:
            zip_file = zip_files[0]
            print(f"Found zip file: {zip_file}")
            temp_extract = extract_path / "temp_extract"
            temp_extract.mkdir(exist_ok=True)

            print("Extracting zip file...")
            with zipfile.ZipFile(zip_file, 'r') as zip_ref:
                zip_ref.extractall(temp_extract)
            print("✓ Zip file extracted")
    elif zip_source.suffix == '.zip':
        print(f"Extracting zip file: {zip_source}")
        temp_extract = extract_path / "temp_extract"
        temp_extract.mkdir(exist_ok=True)

        with zipfile.ZipFile(zip_source, 'r') as zip_ref:
            zip_ref.extractall(temp_extract)
        print("✓ Zip file extracted")
    else:
        print(f"Error: {zip_path} is neither a directory nor a .zip file")
        return None, {}, {}

    # NEW: Pattern to extract celebrity ID from folder name
    folder_pattern = re.compile(r'images__(\d+)_')

    # NEW: Check if already organized in folders
    existing_folders = [d for d in temp_extract.iterdir() if d.is_dir() and folder_pattern.match(d.name)]

    if existing_folders:
        # Images are already organized in folders
        print("\nImages already organized in folders, preserving structure...")
        celebrity_counts = defaultdict(int)
        celebrity_names = {}  # NEW: Map ID to folder name

        for folder in existing_folders:
            match = folder_pattern.match(folder.name)
            if match:
                celebrity_id = match.group(1)
                celebrity_names[int(celebrity_id)] = folder.name  # Store folder name

                # Create output directory with celebrity ID
                celeb_dir = extract_path / celebrity_id
                celeb_dir.mkdir(exist_ok=True)

                # Copy all images from this folder
                images = []
                for ext in ['*.jpg', '*.jpeg', '*.png', '*.JPG', '*.JPEG', '*.PNG']:
                    images.extend(folder.glob(ext))

                for img_file in images:
                    if not img_file.name.startswith('._'):
                        dest_path = celeb_dir / img_file.name
                        shutil.copy2(img_file, dest_path)
                        celebrity_counts[celebrity_id] += 1

        organized_count = sum(celebrity_counts.values())
    else:
        # Images are loose, need to organize
        print("\nFinding image files...")
        image_files = []
        for ext in ['*.jpg', '*.jpeg', '*.png', '*.JPG', '*.JPEG', '*.PNG']:
            image_files.extend(temp_extract.rglob(ext))

        image_files = [f for f in image_files if not f.name.startswith('._')]
        image_files = sorted(image_files)

        print(f"Found {len(image_files)} image files")

        if len(image_files) == 0:
            print("Error: No images found!")
            return None, {}, {}

        # Pattern to match: images__celebrityID_*
        pattern = re.compile(r'images__(\d+)_')

        celebrity_counts = defaultdict(int)
        celebrity_names = {}  # NEW: Map ID to extracted name
        organized_count = 0

        print("\nOrganizing images...")
        for idx, img_file in enumerate(image_files):
            filename = img_file.name
            match = pattern.match(filename)

            if match:
                celebrity_id = match.group(1)
                # NEW: Extract full folder name pattern from filename
                folder_name_match = re.match(r'(images__\d+_)', filename)
                if folder_name_match and int(celebrity_id) not in celebrity_names:
                    celebrity_names[int(celebrity_id)] = folder_name_match.group(1).rstrip('_')
            elif celebrity_mapping and filename in celebrity_mapping:
                celebrity_id = str(celebrity_mapping[filename])
            elif images_per_celebrity:
                celebrity_id = str(idx // images_per_celebrity)
            else:
                celebrity_id = str(idx % num_classes)

            celeb_dir = extract_path / celebrity_id
            celeb_dir.mkdir(exist_ok=True)

            dest_path = celeb_dir / filename
            try:
                shutil.copy2(img_file, dest_path)
                celebrity_counts[celebrity_id] += 1
                organized_count += 1

                if organized_count % 100 == 0:
                    print(f"Progress: {organized_count}/{len(image_files)} images...")
            except Exception as e:
                print(f"Error copying {filename}: {e}")

    # Clean up temp folder
    if temp_extract != zip_source and temp_extract.exists() and str(temp_extract).endswith('temp_extract'):
        shutil.rmtree(temp_extract)

    print(f"\n✓ Successfully organized {organized_count} images")
    print(f"✓ Found {len(celebrity_counts)} celebrity classes")

